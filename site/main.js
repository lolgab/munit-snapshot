// The literal rules of snaptest's SnapshotSource, so the page writes snapshots
// exactly like the library does

const isControl = (c) => {
  const n = c.charCodeAt(0);
  return n <= 0x1f || (n >= 0x7f && n <= 0x9f);
};

function escaped(value) {
  let out = '"';
  for (const c of value) {
    if (c === '"') out += '\\"';
    else if (c === "\\") out += "\\\\";
    else if (c === "\n") out += "\\n";
    else if (c === "\r") out += "\\r";
    else if (c === "\t") out += "\\t";
    else if (isControl(c))
      out += "\\u" + c.charCodeAt(0).toString(16).padStart(4, "0");
    else out += c;
  }
  return out + '"';
}

function literal(value, indent) {
  const chars = [...value];
  const tripleQuotable =
    !value.includes('"""') &&
    chars.every((c) => c === "\n" || c === "\t" || !isControl(c));
  const plain = chars.every((c) => c !== '"' && c !== "\\" && !isControl(c));
  if (plain) return escaped(value);
  if (tripleQuotable && value.includes("\n"))
    return (
      '"""|' +
      value.split("\n").join("\n" + " ".repeat(indent + 3) + "|") +
      '""".stripMargin'
    );
  if (tripleQuotable && !value.startsWith('"')) return '"""' + value + '"""';
  return escaped(value);
}

function entry(key, value) {
  const k = escaped(key);
  const v = literal(value, 6);
  if (!v.includes("\n") && 4 + k.length + 4 + v.length + 1 <= 100)
    return `    ${k} -> ${v},`;
  return `    ${k} ->\n      ${v},`;
}

function source(pkg, suite, entries) {
  return [
    "// Generated by snaptest, update with SNAPTEST=always",
    "// format: off",
    "// $COVERAGE-OFF$",
    `package ${pkg}`,
    "",
    `/** Snapshots of [[${suite}]] */`,
    `object ${suite}Snapshots extends snaptest.Snapshots {`,
    "  def entries = Seq(",
    ...entries.map(([k, v]) => entry(k, v)),
    "  )",
    "}",
  ].join("\n");
}

// A small highlighter for the Scala shown in fragments

const escapeHtml = (s) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function highlight(code, { numbers = false, mark = -1 } = {}) {
  const html = escapeHtml(code).replace(
    /(\/\/.*$|\/\*\*.*?\*\/)|("""[\s\S]*?"""(?!")|"(?:[^"\\\n]|\\.)*")|\b(package|object|extends|def|class|import|val)\b/gm,
    (m, comment, string, keyword) =>
      comment
        ? `<span class="c">${comment}</span>`
        : string
          ? `<span class="s">${string}</span>`
          : `<span class="k">${keyword}</span>`
  );
  if (!numbers) return html;
  return html
    .split("\n")
    .map(
      (line, i) =>
        `<span class="${i + 1 === mark ? "hl" : ""}"><span class="ln">${i + 1}</span>${line}</span>`
    )
    .join("\n");
}

function lineOf(text, key) {
  const prefix = `    ${escaped(key)} ->`;
  return text.split("\n").findIndex((l) => l.startsWith(prefix)) + 1;
}

function diff(expected, obtained) {
  const a = expected.split("\n");
  const b = obtained.split("\n");
  const lines = [];
  let i = 0;
  while (i < Math.max(a.length, b.length)) {
    if (a[i] === b[i]) lines.push(` ${a[i]}`);
    else {
      if (i < a.length) lines.push(`-${a[i]}`);
      if (i < b.length) lines.push(`+${b[i]}`);
    }
    i++;
  }
  return lines;
}

function failure(path, file, key, expected, obtained) {
  const line = lineOf(file, key);
  const d = diff(expected, obtained)
    .map((l) =>
      l.startsWith("-")
        ? `<span class="del">${escapeHtml(l)}</span>`
        : l.startsWith("+")
          ? `<span class="add">${escapeHtml(l)}</span>`
          : escapeHtml(l)
    )
    .join("\n");
  return (
    `<span class="fail">Snapshot '${escapeHtml(key)}' does not match, rerun with SNAPTEST=always to update it</span>\n` +
    `  at ${path}:${line}\n=> Diff (- expected, + obtained)\n${d}`
  );
}

// Hero: a snapshot of this page

function pageSnapshot() {
  const root = document.querySelector("[data-page-snapshot]");
  if (!root) return;
  const code = root.querySelector(".code");
  const result = root.querySelector(".page-snapshot__result");
  const input = root.querySelector("input");
  const accept = root.querySelector("[data-accept]");
  const lines = [...document.querySelectorAll(".hero h1 [data-line]")];
  const path = "snapshots/HomePageTestSnapshots.scala";

  const observe = () => [
    ["headline", input.value],
    ["viewport", `${window.innerWidth} × ${window.innerHeight}`],
  ];
  let recorded = observe();

  const render = () => {
    const obtained = observe();
    const file = source("site", "HomePageTest", recorded);
    const mismatches = obtained.filter(
      ([k, v], i) => recorded[i][1] !== v
    );
    const first = mismatches[0];
    code.innerHTML = highlight(file, {
      numbers: true,
      mark: first ? lineOf(file, first[0]) : -1,
    });
    if (first) {
      const [key, value] = first;
      const expected = recorded.find(([k]) => k === key)[1];
      result.classList.add("is-failed");
      result.innerHTML = failure(path, file, key, expected, value);
      accept.hidden = false;
    } else {
      result.classList.remove("is-failed");
      result.innerHTML = `<span class="ok">+ HomePageTest: 2 snapshots match</span>`;
      accept.hidden = true;
    }
  };

  input.addEventListener("input", () => {
    const words = input.value.trim().split(/\s+/);
    const half = Math.ceil(words.length / 2);
    lines[0].textContent = words.slice(0, half).join(" ");
    lines[1].textContent = words.slice(half).join(" ");
    render();
  });
  accept.addEventListener("click", () => {
    recorded = observe();
    render();
  });
  let resizing;
  window.addEventListener("resize", () => {
    cancelAnimationFrame(resizing);
    resizing = requestAnimationFrame(render);
  });
  render();
}

// Showcase: any value, the entry snaptest writes for it

const presets = {
  "case class": 'User(name = "ada", roles = List("admin", "dev"))',
  "multi-line": 'List(\n  "item1",\n  "item2",\n  "item3"\n)',
  string: "Hello, World",
  "tricky string": '"quoted" and \\ a backslash\r\n',
};

function showcase() {
  const root = document.querySelector("[data-showcase]");
  if (!root) return;
  const textarea = root.querySelector("textarea");
  const out = root.querySelector("[data-showcase-out]");
  const buttons = [...root.querySelectorAll("[data-preset]")];
  const render = () => {
    out.innerHTML = highlight(
      ["  def entries = Seq(", entry("your test", textarea.value), "  )"].join(
        "\n"
      )
    );
  };
  buttons.forEach((button) =>
    button.addEventListener("click", () => {
      textarea.value = presets[button.dataset.preset];
      buttons.forEach((b) => b.setAttribute("aria-pressed", b === button));
      render();
    })
  );
  textarea.addEventListener("input", () => {
    buttons.forEach((b) => b.setAttribute("aria-pressed", "false"));
    render();
  });
  render();
}

// How it works: the statement in view sets the state of the pinned fragment

function steps() {
  const stage = document.querySelector(".stage");
  const items = [...document.querySelectorAll(".step")];
  if (!stage || !("IntersectionObserver" in window)) return;
  const observer = new IntersectionObserver(
    (records) => {
      records.forEach((r) => {
        if (!r.isIntersecting) return;
        items.forEach((s) => s.classList.toggle("is-active", s === r.target));
        stage.dataset.state = r.target.dataset.state;
      });
    },
    { rootMargin: "-45% 0px -45% 0px" }
  );
  items.forEach((s) => observer.observe(s));
}

// Entrances, once per element. Anything above the bottom of the screen is
// shown, so jumping down the page never leaves hidden content behind.

function reveals() {
  let pending = [...document.querySelectorAll("[data-reveal]")];
  const check = () => {
    const limit = window.innerHeight * 0.92;
    pending = pending.filter((el) => {
      if (el.getBoundingClientRect().top < limit) {
        el.classList.add("is-in");
        return false;
      }
      return true;
    });
    if (!pending.length) window.removeEventListener("scroll", onScroll);
  };
  let frame;
  const onScroll = () => {
    cancelAnimationFrame(frame);
    frame = requestAnimationFrame(check);
  };
  window.addEventListener("scroll", onScroll, { passive: true });
  window.addEventListener("resize", onScroll);
  check();
}

// Copy buttons

function copyButtons() {
  document.querySelectorAll("[data-copy]").forEach((button) => {
    button.addEventListener("click", async () => {
      const text = document.querySelector(button.dataset.copy).textContent;
      try {
        await navigator.clipboard.writeText(text);
        const label = button.textContent;
        button.textContent = "Copied";
        setTimeout(() => (button.textContent = label), 1600);
      } catch {
        // The text stays selectable
      }
    });
  });
}

// Static code blocks

function highlightBlocks() {
  document.querySelectorAll("[data-scala]").forEach((el) => {
    el.innerHTML = highlight(el.textContent, {
      numbers: el.hasAttribute("data-numbers"),
    });
  });
}

// Guide: the contents follow the section being read

function contents() {
  const links = [...document.querySelectorAll(".toc a")];
  if (!links.length || !("IntersectionObserver" in window)) return;
  const targets = links
    .map((a) => document.querySelector(a.getAttribute("href")))
    .filter(Boolean);
  const observer = new IntersectionObserver(
    (records) =>
      records.forEach((r) => {
        if (!r.isIntersecting) return;
        links.forEach((a) =>
          a.classList.toggle("is-current", a.getAttribute("href") === `#${r.target.id}`)
        );
      }),
    { rootMargin: "0px 0px -70% 0px" }
  );
  targets.forEach((t) => observer.observe(t));
}

// Guide: the parts of each section arrive in reading order

function guideEntrances() {
  document.querySelectorAll(".doc section").forEach((section) => {
    [...section.children].forEach((el, i) => {
      el.setAttribute("data-reveal", "");
      el.style.setProperty("--i", Math.min(i, 4));
    });
  });
}

highlightBlocks();
guideEntrances();
