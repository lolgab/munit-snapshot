package snaptest

class SnapshotSourceTest extends munit.FunSuite:

  // Expected sources use ''' for """, which cannot appear in them
  private def source(s: String) = s.stripMargin.replace("'''", "\"\"\"")

  test("render") {
    assertNoDiff(
      SnapshotSource.render(
        SnapshotSource.names("a.b.Foo"),
        Seq(
          "one" -> "1",
          "quotes" -> "say \"hi\"",
          "long" -> ("x" * 100),
          "two lines" -> "x\n  |y"
        )
      ),
      source(
        s"""|// Generated by snaptest, update with SNAPTEST=always
            |// format: off
            |// $$COVERAGE-OFF$$
            |package a.b
            |
            |/** Snapshots of [[Foo]] */
            |object FooSnapshots extends snaptest.Snapshots {
            |  def entries = Seq(
            |    "one" -> "1",
            |    "quotes" -> '''say "hi"''',
            |    "long" ->
            |      "${"x" * 100}",
            |    "two lines" ->
            |      '''|x
            |         |  |y'''.stripMargin,
            |  )
            |}
            |"""
      )
    )
  }

  test("render splits entries in parts") {
    assertNoDiff(
      SnapshotSource.render(
        SnapshotSource.names("Foo"),
        Seq("a" -> "1", "b" -> "2", "c" -> "3"),
        partSize = 2
      ),
      source(
        """|// Generated by snaptest, update with SNAPTEST=always
           |// format: off
           |// $COVERAGE-OFF$
           |
           |/** Snapshots of [[Foo]] */
           |object FooSnapshots extends snaptest.Snapshots {
           |  def entries = part0 ++ part1
           |
           |  private def part0 = Seq(
           |    "a" -> "1",
           |    "b" -> "2",
           |  )
           |
           |  private def part1 = Seq(
           |    "c" -> "3",
           |  )
           |}
           |"""
      )
    )
  }

  test("render escapes names") {
    assertNoDiff(
      SnapshotSource.render(
        SnapshotSource.Names("type.ok", "my suite", "my snapshots"),
        Nil
      ),
      source(
        """|// Generated by snaptest, update with SNAPTEST=always
           |// format: off
           |// $COVERAGE-OFF$
           |package `type`.ok
           |
           |/** Snapshots of [[my suite]] */
           |object `my snapshots` extends snaptest.Snapshots {
           |  def entries = Seq(
           |  )
           |}
           |"""
      )
    )
  }

  test("names") {
    assertEquals(
      SnapshotSource.names("a.b.FooTest"),
      SnapshotSource.Names("a.b", "FooTest", "FooTestSnapshots")
    )
    assertEquals(
      SnapshotSource.names("a.Outer$Inner$"),
      SnapshotSource.Names("a", "Outer.Inner", "Outer_InnerSnapshots")
    )
    assertEquals(SnapshotSource.names("FooTest").fullName, "FooTestSnapshots")
    assertEquals(
      SnapshotSource.names("a.FooTest").fullName,
      "a.FooTestSnapshots"
    )
  }

  test("line") {
    val names = SnapshotSource.names("a.Foo")
    val entries = Seq("a" -> "x\ny", "b \"quoted\"" -> "1", "c" -> "2")
    val lines = SnapshotSource.render(names, entries).linesIterator.toVector
    assertEquals(
      SnapshotSource.line(names, entries, "a").map(l => lines(l - 1)),
      Some("    \"a\" ->")
    )
    assertEquals(
      SnapshotSource
        .line(names, entries, "b \"quoted\"")
        .map(l => lines(l - 1)),
      Some("    \"b \\\"quoted\\\"\" -> \"1\",")
    )
    assertEquals(SnapshotSource.line(names, entries, "missing"), None)
  }

  private def literal(value: String) = SnapshotSource.literal(value, indent = 0)

  test("literal") {
    assertEquals(literal("plain"), "\"plain\"")
    assertEquals(literal(""), "\"\"")
    assertEquals(literal("""say "hi" \o/"""), source("""'''say "hi" \o/'''"""))
    assertEquals(literal("ends with \""), source("'''ends with \"'''"))
    assertEquals(
      literal("\"starts with a quote"),
      "\"\\\"starts with a quote\""
    )
    assertEquals(literal("a\"\"\"b"), "\"a\\\"\\\"\\\"b\"")
    assertEquals(literal("crlf\r\n\u0001"), "\"crlf\\r\\n\\u0001\"")
    assertEquals(
      literal("\"a\nb\"\n"),
      source(
        """|'''|"a
           |   |b"
           |   |'''.stripMargin"""
      )
    )
  }

  test("literal splits long values") {
    assertEquals(
      SnapshotSource.literal("abcdefg", indent = 0, chunkSize = 3),
      source(
        """|List(
           |  "abc",
           |  "def",
           |  "g",
           |).mkString"""
      )
    )
    // A surrogate pair is never split
    assertEquals(
      SnapshotSource.literal("ab😀c", indent = 0, chunkSize = 3),
      "List(\n  \"ab\",\n  \"😀c\",\n).mkString"
    )
  }
