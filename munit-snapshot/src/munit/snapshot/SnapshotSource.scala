package munit.snapshot

/** Generates the Scala source of the [[Snapshots]] object of a suite:
  *
  * {{{
  * package example
  *
  * object ExampleSnapshotTestSnapshots extends munit.snapshot.Snapshots {
  *   def entries = Seq(
  *     "one plus one" -> "2",
  *     "greeting" ->
  *       """|Hello
  *          |World""".stripMargin,
  *   )
  * }
  * }}}
  *
  * Storing snapshots as Scala sources means that build tools recompile and
  * rerun the tests when they change, without any configuration.
  */
private[snapshot] object SnapshotSource:

  /** Maximum length of a string literal, the JVM limits string constants to
    * 65535 bytes and a character takes up to 3 bytes
    */
  val ChunkSize = 20000

  /** Maximum number of entries in a method, each one takes about 30 bytes of
    * bytecode and the JVM limits methods to 65535 bytes
    */
  val PartSize = 1000

  /** Line length up to which an entry is kept on a single line */
  private val LineWidth = 100

  /** Package of a suite, its name in the package and the name of its snapshots
    * object
    */
  final case class Names(pkg: String, suite: String, obj: String):
    def fullName: String = if pkg.isEmpty then obj else s"$pkg.$obj"

  def names(suiteClassName: String): Names =
    val i = suiteClassName.lastIndexOf('.')
    val name = suiteClassName.substring(i + 1).stripSuffix("$")
    Names(
      if i < 0 then "" else suiteClassName.substring(0, i),
      name.replace('$', '.'),
      name.replace('$', '_') + "Snapshots"
    )

  def render(
      names: Names,
      entries: Seq[(String, String)],
      partSize: Int = PartSize
  ): String =
    val sb = StringBuilder()
    sb ++= "// Generated by munit-snapshot, update with "
    sb ++= s"${SnapshotMode.EnvVar}=always\n"
    sb ++= "// format: off\n"
    sb ++= "// $COVERAGE-OFF$\n"
    if names.pkg.nonEmpty then
      sb ++= s"package ${names.pkg.split('.').map(identifier).mkString(".")}\n"
    // A link to the suite, which IDEs can navigate
    sb ++= s"\n/** Snapshots of [[${names.suite}]] */\n"
    sb ++= s"object ${identifier(names.obj)} extends munit.snapshot.Snapshots {\n"
    def seq(definition: String, part: Seq[(String, String)]): Unit =
      sb ++= s"  $definition = Seq(\n"
      for (key, value) <- part do sb ++= entry(key, value)
      sb ++= "  )\n"
    val parts = entries.grouped(partSize).toSeq
    if parts.size <= 1 then seq("def entries", entries)
    else
      sb ++= parts.indices
        .map(i => s"part$i")
        .mkString("  def entries = ", " ++ ", "\n")
      for (part, i) <- parts.zipWithIndex do
        sb += '\n'
        seq(s"private def part$i", part)
    sb ++= "}\n"
    sb.result()

  /** Line number of the snapshot `key` in the source rendered from `entries`
    */
  def line(
      names: Names,
      entries: Seq[(String, String)],
      key: String
  ): Option[Int] =
    val prefix = s"    ${escaped(key)} ->"
    render(names, entries).linesIterator.indexWhere(_.startsWith(prefix)) match
      case -1 => None
      case i  => Some(i + 1)

  private def entry(key: String, value: String): String =
    val k = escaped(key)
    val v = literal(value, indent = 6)
    if !v.contains('\n') && 4 + k.length + 4 + v.length + 1 <= LineWidth then
      s"    $k -> $v,\n"
    else s"    $k ->\n      $v,\n"

  /** A Scala expression evaluating to `value`, as readable as possible, to be
    * placed at column `indent`
    */
  def literal(value: String, indent: Int, chunkSize: Int = ChunkSize): String =
    if value.length <= chunkSize then single(value, indent)
    else
      val pad = " " * (indent + 2)
      chunks(value, chunkSize)
        .map(c => s"$pad${single(c, indent + 2)},\n")
        .mkString("List(\n", "", s"${" " * indent}).mkString")

  private def single(value: String, indent: Int): String =
    val tripleQuotable =
      !value.contains("\"\"\"") &&
        value.forall(c => c == '\n' || c == '\t' || !c.isControl)
    val plain = value.forall(c => c != '"' && c != '\\' && !c.isControl)
    if plain then escaped(value)
    else if tripleQuotable && value.contains('\n') then
      // Every line gets a margin, so any content survives `stripMargin`
      value
        .split("\n", -1)
        .mkString("\"\"\"|", s"\n${" " * (indent + 3)}|", "\"\"\".stripMargin")
    else if tripleQuotable && !value.startsWith("\"") then s"\"\"\"$value\"\"\""
    else escaped(value)

  private def escaped(value: String): String =
    val sb = StringBuilder("\"")
    value.foreach {
      case '"'              => sb ++= "\\\""
      case '\\'             => sb ++= "\\\\"
      case '\n'             => sb ++= "\\n"
      case '\r'             => sb ++= "\\r"
      case '\t'             => sb ++= "\\t"
      case c if c.isControl => sb ++= f"\\u${c.toInt}%04x"
      case c                => sb += c
    }
    sb += '"'
    sb.result()

  // Splits without separating the two halves of a surrogate pair
  private def chunks(value: String, size: Int): Seq[String] =
    val result = Seq.newBuilder[String]
    var start = 0
    while start < value.length do
      var end = (start + size).min(value.length)
      if end < value.length && value(end - 1).isHighSurrogate then end -= 1
      result += value.substring(start, end)
      start = end
    result.result()

  private val keywords = (
    "abstract case catch class def do else enum export extends false " +
      "final finally for given if implicit import lazy match new null " +
      "object override package private protected return sealed super then " +
      "throw trait true try type val var while with yield"
  ).split(' ').toSet

  private def identifier(name: String): String =
    val simple = name.nonEmpty &&
      (name.head.isLetter || name.head == '_') &&
      name.forall(c => c.isLetterOrDigit || c == '_')
    if simple && !keywords(name) then name else s"`$name`"
